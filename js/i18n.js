var currentLang = localStorage.getItem('wedding_lang') || 'ru';

function t(key) {
    return (translations[currentLang] && translations[currentLang][key]) ||
        (translations.ru && translations.ru[key]) ||
        key;
}

function applyLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('wedding_lang', lang);
    document.documentElement.lang = lang === 'ky' ? 'ky' : 'ru';

    $('[data-i18n]').each(function () {
        var key = $(this).attr('data-i18n');
        var value = t(key);
        if (value.indexOf('<') !== -1) {
            $(this).html(value);
        } else {
            $(this).text(value);
        }
    });

    $('[data-i18n-placeholder]').each(function () {
        $(this).attr('placeholder', t($(this).attr('data-i18n-placeholder')));
    });

    $('.lang-btn').removeClass('active');
    $('.lang-btn[data-lang="' + lang + '"]').addClass('active');
}

$(document).ready(function () {
    applyLanguage(currentLang);

    $('.lang-btn').on('click', function (e) {
        e.preventDefault();
        applyLanguage($(this).data('lang'));
    });
});
